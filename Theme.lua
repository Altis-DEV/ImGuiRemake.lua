function Theme:CreateTheme(themeName, colorTable)
    assert(type(themeName) == "string", "Theme name must be a string")
    assert(type(colorTable) == "table", "Theme colors must be a table")

    local newTheme = {}

    for key, value in pairs(self.Themes.Default) do
        newTheme[key] = value
    end

    for key, value in pairs(colorTable) do
        newTheme[key] = value
    end

    self.Themes[themeName] = newTheme
    return newTheme
end

function Theme:GetTheme(themeName)
    return self.Themes[themeName] or self.Themes.Default
end

return Theme
